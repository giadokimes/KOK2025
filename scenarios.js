/**
 * Επιστρέφει τα IDs που ταιριάζουν με το query βάσει σεναρίων.
 * Λογική: αν ΟΛΕΣ οι λέξεις μιας phrase βρίσκονται στο query → match.
 *
 * @param {string} query - Το query του χρήστη (normalized, χωρίς τόνους)
 * @returns {Set<number>} - Set με IDs που boostάρονται
 */
function getScenarioMatches(query) {
    if (!query || query.length < 3) return new Set();
    const q = query.toLowerCase().trim();
    const qWords = q.split(/\s+/).filter(w => w.length > 0);
    const matchedIds = new Set();

    for (const scenario of scenarios) {
        for (const phrase of scenario.phrases) {
            const phraseWords = phrase.split(/\s+/).filter(w => w.length > 0);
            // Όλες οι λέξεις της phrase πρέπει να είναι στο query
            const allMatch = phraseWords.every(pw =>
                qWords.some(qw => qw.startsWith(pw) || pw.startsWith(qw))
            );
            if (allMatch && phraseWords.length > 0) {
                scenario.ids.forEach(id => matchedIds.add(id));
                break; // δεν χρειάζεται να ελέγξουμε άλλες phrases του ίδιου scenario
            }
        }
    }
    return matchedIds;
}

/**
 * Επιστρέφει τα scenarios που ταιριάζουν (για auto-suggest).
 *
 * @param {string} query
 * @returns {Array<{label: string, ids: number[]}>}
 */
function findMatchingScenarios(query) {
    if (!query || query.length < 2) return [];
    const q = query.toLowerCase().trim();
    const qWords = q.split(/\s+/).filter(w => w.length > 0);
    const results = [];

    for (const scenario of scenarios) {
        const matches = scenario.phrases.some(phrase => {
            const phraseWords = phrase.split(/\s+/).filter(w => w.length > 0);
            return phraseWords.every(pw =>
                qWords.some(qw => qw.startsWith(pw) || pw.startsWith(qw))
            );
        });
        if (matches) results.push({ label: scenario.label, ids: scenario.ids });
    }
    return results;
}