// ============================================================
// Αναζήτηση πινακίδας στο signImageMap, δοκιμάζοντας ΟΛΟΥΣ
// τους πιθανούς συνδυασμούς Unicode για το πρώτο γράμμα:
//   - ελληνικό Ρ  (U+03A1)
//   - λατινικό P  (U+0050)
//   - λατινικό R  (U+0052)
// Έτσι δεν μας νοιάζει αν το data.js ή το signs-data.json έχουν
// διαφορετικό "P" οπτικά ίδιο αλλά διαφορετικό byte.
// ============================================================
function findSignImage(prefix, number) {
    if (typeof signImageMap === 'undefined' || !signImageMap) return null;
    // Το κείμενο των παραβάσεων γράφει τα επιθήματα με ελληνικούς
    // χαρακτήρες (π.χ. Ρ-50α), αλλά το αυτόματο workflow που παράγει
    // το signs-data.json αποθηκεύει μερικά με λατινικούς (Ρ-50a).
    // Δοκιμάζουμε και τις δύο γραφές για κάθε πιθανό πρόθεμα.
    const latinNumber = number.replace(/α/g, 'a').replace(/β/g, 'b').replace(/δ/g, 'd');
    const numbers = number === latinNumber ? [number] : [number, latinNumber];
    const candidates = [];
    for (const n of numbers) {
        candidates.push('Ρ-' + n, 'P-' + n, 'R-' + n);
    }
    for (const c of candidates) {
        if (signImageMap[c]) return { code: c, url: signImageMap[c] };
    }
    return null;
}

function replaceSignCodes(text, violationId) {
    if (!text) return text;
    return text.replace(/([ΡP])-([\dαβδ]+)/g, function(match, prefix, number) {
        const found = findSignImage(prefix, number);
        if (found) {
            return `<img src="${found.url}" class="sign-img" alt="${found.code}" title="${found.code}" loading="lazy" onclick="openSignModal('${found.url}', '${found.code}', ${violationId})">`;
        }
        return match;
    });
}

// ============================================================
// Σειρά εικονιδίων πινακίδων (chip row) — αντί να «σπάμε» το
// ρέον κείμενο του τίτλου με inline εικόνες (κάποιες παραβάσεις
// αναφέρουν έως και 28 πινακίδες μαζί), βγάζουμε τους κωδικούς
// σε ξεχωριστή, wrap-able σειρά κάτω από τον τίτλο.
// Πινακίδες χωρίς διαθέσιμη εικόνα εμφανίζονται ως ετικέτα
// κειμένου, ώστε το κενό να φαίνεται αντί να εξαφανίζεται σιωπηλά.
// ============================================================
function extractSignRefs(text) {
    if (!text) return [];
    const refs = [];
    const seen = new Set();
    const re = /([ΡP])-([\dαβδ]+)/g;
    let m;
    while ((m = re.exec(text)) !== null) {
        const found = findSignImage(m[1], m[2]);
        const code = found ? found.code : ('Ρ-' + m[2]);
        if (seen.has(code)) continue;
        seen.add(code);
        refs.push({ code: code, url: found ? found.url : null });
    }
    return refs;
}

function renderSignIconsRow(text, violationId) {
    const refs = extractSignRefs(text);
    if (!refs.length) return '';
    const chips = refs.map(function(r) {
        if (r.url) {
            return `<img src="${r.url}" class="sign-img" alt="${r.code}" title="${r.code}" loading="lazy" onclick="openSignModal('${r.url}', '${r.code}', ${violationId})">`;
        }
        return `<span class="sign-img sign-img-missing" title="${r.code} — δεν βρέθηκε εικόνα">${r.code}</span>`;
    }).join('');
    return `<div class="sign-icons-row">${chips}</div>`;
}

// ============================================================
// Καθαρή εκδοχή τίτλου για εμφάνιση — αφαιρεί τους κωδικούς
// πινακίδων (Ρ-40, Ρ-50α, ...) από το κείμενο, αφού πλέον
// εμφανίζονται ήδη σαν εικονίδια στη sign-icons-row. Χωρίς αυτό,
// κάθε κωδικός φαινόταν διπλά (μία ως κείμενο, μία ως εικόνα) και
// γέμιζε την κάρτα. Το v.name το ίδιο ΔΕΝ αλλάζει — μόνο ό,τι
// εμφανίζεται. Η αναζήτηση/εξαγωγή PDF συνεχίζουν να δουλεύουν
// στο πλήρες αρχικό κείμενο.
// ============================================================
function stripSignCodesForDisplay(text) {
    if (!text) return text;
    let out = text;
    out = out.replace(/([ΡP])-([\dαβδ]+)/g, '');
    out = out.replace(/\(\s*\)/g, '');
    out = out.replace(/,(\s*,)+/g, ',');
    out = out.replace(/\(\s*,\s*/g, '(');
    out = out.replace(/,\s*\)/g, ')');
    out = out.replace(/^\s*,\s*/, '');
    out = out.replace(/\s*,\s*$/, '');
    out = out.replace(/(\S)\/(?=\s|$)/g, '$1');
    out = out.replace(/^\s*\/\s*/, '');
    out = out.replace(/\s{2,}/g, ' ');
    out = out.trim();
    out = out.replace(/[\s,/]+$/, '');
    if (out === 'Παραβίαση') out = 'Παραβίαση πινακίδων';
    return out || text;
}

function openSignModal(imgSrc, signCode, violationId) {
    const modal = document.getElementById('signModal');
    const modalImg = document.getElementById('modalSignImg');
    const modalName = document.getElementById('modalSignName');
    const modalDetails = document.getElementById('modalSignDetails');

    modalImg.src = imgSrc;
    modalImg.alt = signCode;

    const rawDescription = signDescriptions[signCode] || signCode;
    const isUnverified = rawDescription.includes('ΜΗ ΕΠΙΒΕΒΑΙΩΜΕΝΟ');
    const description = rawDescription.replace(' (ΜΗ ΕΠΙΒΕΒΑΙΩΜΕΝΟ)', '');
    const warningHtml = isUnverified
        ? '<div class="sign-unverified-warning">' + icon('alertTriangle', 'icon-svg icon-inline') + ' Η περιγραφή αυτής της πινακίδας δεν έχει ακόμη επιβεβαιωθεί με επίσημη πηγή — έλεγξέ την πριν τη χρησιμοποιήσεις.</div>'
        : '';
    const violation = data.find(v => v.id === violationId);
    if (violation) {
        modalName.textContent = signCode + ' – ' + description;
        let details = '';
        if (violation.fine) details += 'Πρόστιμο: ' + formatFine(violation.fine);
        if (violation.suspend && violation.suspend !== '-') {
            if (details) details += ' | ';
            details += 'Κύρωση: ' + violation.suspend;
        }
        if (violation.points > 0) {
            if (details) details += ' | ';
            details += 'Βαθμοί ΣΕΣΟ: ' + violation.points;
        }
        modalDetails.innerHTML = warningHtml + '<div>' + (details || 'Δεν υπάρχουν διαθέσιμες πληροφορίες ποινών.') + '</div>';
    } else {
        modalName.textContent = signCode + ' – ' + description;
        modalDetails.innerHTML = warningHtml + '<div>Πινακίδα χωρίς αντιστοιχισμένη παράβαση.</div>';
    }

    modal.style.display = 'flex';
}

function closeSignModal() {
    document.getElementById('signModal').style.display = 'none';
}

document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeSignModal();
});

document.getElementById('signModal').addEventListener('click', (e) => {
    if (e.target === e.currentTarget) closeSignModal();
});