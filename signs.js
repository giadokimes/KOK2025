function replaceSignCodes(text, violationId) {
    if (!text) return text;
    return text.replace(/([ΡP])-([\dαβδ]+)/g, function(match, prefix, number) {
        const code = 'Ρ-' + number;
        const imgUrl = signImageMap[code];
        if (imgUrl) {
            return `<img src="${imgUrl}" class="sign-img" alt="${code}" title="${code}" loading="lazy" onclick="openSignModal('${imgUrl}', '${code}', ${violationId})">`;
        }
        return match;
    });
}

function openSignModal(imgSrc, signCode, violationId) {
    const modal = document.getElementById('signModal');
    const modalImg = document.getElementById('modalSignImg');
    const modalName = document.getElementById('modalSignName');
    const modalDetails = document.getElementById('modalSignDetails');

    modalImg.src = imgSrc;
    modalImg.alt = signCode;

    const rawDescription = signDescriptions[signCode] || signCode;
    const isUnverified = rawDescription.includes('ΜΗ ΕΠΙΒΕΒΑΙΩΜΕΝΟ');
    const description = rawDescription.replace(' (ΜΗ ΕΠΙΒΕΒΑΙΩΜΕΝΟ)', '');
    const warningHtml = isUnverified
        ? '<div class="sign-unverified-warning">' + icon('alertTriangle', 'icon-svg icon-inline') + ' Η περιγραφή αυτής της πινακίδας δεν έχει ακόμη επιβεβαιωθεί με επίσημη πηγή — έλεγξέ την πριν τη χρησιμοποιήσεις.</div>'
        : '';
    // Χρησιμοποιούμε το ΣΥΓΚΕΚΡΙΜΕΝΟ id της κάρτας που πατήθηκε — όχι
    // αναζήτηση με includes() σε όλη τη βάση, που έδινε λάθος αποτέλεσμα
    // σε κάρτες με πολλαπλές πινακίδες.
    const violation = data.find(v => v.id === violationId);
    if (violation) {
        modalName.textContent = signCode + ' – ' + description;
        let details = '';
        if (violation.fine) details += 'Πρόστιμο: ' + formatFine(violation.fine);
        if (violation.suspend && violation.suspend !== '-') {
            if (details) details += ' | ';
            details += 'Κύρωση: ' + violation.suspend;
        }
        if (violation.points > 0) {
            if (details) details += ' | ';
            details += 'Βαθμοί ΣΕΣΟ: ' + violation.points;
        }
        modalDetails.innerHTML = warningHtml + '<div>' + (details || 'Δεν υπάρχουν διαθέσιμες πληροφορίες ποινών.') + '</div>';
    } else {
        modalName.textContent = signCode + ' – ' + description;
        modalDetails.innerHTML = warningHtml + '<div>Πινακίδα χωρίς αντιστοιχισμένη παράβαση.</div>';
    }

    modal.style.display = 'flex';
}

function closeSignModal() {
    document.getElementById('signModal').style.display = 'none';
}

document.addEventListener('keydown', (e) => {
    if (e.key === 'Escape') closeSignModal();
});

document.getElementById('signModal').addEventListener('click', (e) => {
    if (e.target === e.currentTarget) closeSignModal();
});
