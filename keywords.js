// ============================================================
// Ομαδοποίηση κατά πρώτο γράμμα (για το αλφαβητικό ευρετήριο)
// ============================================================
function groupKeywordsByLetter() {
    const groups = {};
    Object.keys(keywordIndex).forEach(kw => {
        const firstLetter = kw.charAt(0).toUpperCase();
        if (!groups[firstLetter]) groups[firstLetter] = [];
        groups[firstLetter].push(kw);
    });
    // Ταξινόμηση γραμμάτων
    const sorted = {};
    Object.keys(groups).sort((a, b) => a.localeCompare(b, 'el')).forEach(letter => {
        sorted[letter] = groups[letter].sort((a, b) => a.localeCompare(b, 'el'));
    });
    return sorted;
}

// ============================================================
// Εύρεση keywords που ταιριάζουν με query
// ============================================================
function findMatchingKeywords(query) {
    if (!query || query.length < 2) return [];
    const q = query.toLowerCase();
    return Object.keys(keywordIndex).filter(kw =>
        kw.toLowerCase().includes(q)
    );
}